#!/usr/bin/env python3
"""Audit and reproduce the nonbinding, source-pinned Unicode vocabulary atlas."""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import unicodedata as ud


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "proposals/unicode-vocabulary-candidates.json"
ATLAS = ROOT / "proposals/unicode-vocabulary-atlas.md"


def load_sources(catalog: dict) -> dict:
    """Read the historical study inputs, not whatever ontology is current later."""
    commit = catalog["source_commit"]
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("source_commit must be a full Git commit ID")
    sources = {}
    for path in ("ontology/ontology.md", "ontology/terms.yaml"):
        result = subprocess.run(
            ["git", "show", f"{commit}:{path}"], cwd=ROOT,
            capture_output=True, check=True,
        )
        if hashlib.sha256(result.stdout).hexdigest() != catalog["source_sha256"][path]:
            raise ValueError(f"source hash mismatch: {path}")
        sources[path] = result.stdout.decode("utf-8")
    return json.loads(sources["ontology/terms.yaml"])


def describe(glyph: str) -> str:
    return "; ".join(f"U+{ord(c):04X} {ud.name(c)}" for c in glyph)


def render(catalog: dict, registry: dict) -> str:
    if catalog["schema_version"] != 1 or catalog["binding"] is not False:
        raise ValueError("expected nonbinding schema version 1")
    if catalog["ontology_version"] != registry["ontology_version"]:
        raise ValueError("ontology version mismatch")
    candidates = catalog["candidates"]
    terms = registry["terms"]
    expected = {term["id"].removeprefix("organon:") for term in terms}
    counts = Counter(row["term"] for row in candidates)
    missing = sorted(expected - counts.keys())
    extra = sorted(counts.keys() - expected)
    duplicates = sorted(term for term, count in counts.items() if count != 1)
    if missing or extra or duplicates:
        raise ValueError(
            f"coverage mismatch: missing={missing}, extra={extra}, duplicates={duplicates}"
        )
    for row in candidates:
        verdict, glyph = row["verdict"], row["glyph"]
        if verdict not in {"trial", "reject", "compose"}:
            raise ValueError(f"invalid verdict: {row['term']}")
        if not isinstance(row["reason"], str) or not row["reason"].strip():
            raise ValueError(f"missing rationale: {row['term']}")
        if verdict == "compose":
            if glyph is not None:
                raise ValueError("compose rows must not assign a glyph")
        else:
            if not isinstance(glyph, str) or not glyph:
                raise ValueError("trial/reject rows require a candidate")
            if any(ud.category(c).startswith("C") for c in glyph):
                raise ValueError(f"control, private-use or unassigned character: {row['term']}")
            describe(glyph)  # Every candidate character must have a Unicode name.
            if glyph.encode("utf-8").decode("utf-8") != glyph:
                raise ValueError(f"UTF-8 round-trip failure: {row['term']}")

    verdicts = Counter(row["verdict"] for row in candidates)
    commit = catalog["source_commit"]
    lines = [
        "# Unicode vocabulary candidate atlas", "",
        "Generated by `python3 scripts/check-unicode-vocabulary.py --write`. "
        "Edit the candidate JSON, not this table. **Nonbinding; not a codebook.**", "",
        "Read the [study](./unicode-vocabulary.md) for method, sources and limits. "
        "`trial` means a labelled mnemonic worth testing; `reject` rejects only "
        "the displayed candidate; `compose` retains the name and explicit "
        "structure rather than proposing a standalone mark.", "",
        f"Coverage: **{len(terms)} active entries**; "
        f"**{verdicts['trial']} trial**, **{verdicts['reject']} reject**, "
        f"**{verdicts['compose']} compose**. No assignment claims semantic equivalence.", "",
        f"Source: ontology v{catalog['ontology_version']} at "
        f"[{commit[:7]}](https://github.com/sadasant/organon/commit/{commit}). "
        "Term links below open the working ontology; use that commit to recover "
        "the definitions assessed if the ontology has since changed.", "",
        "## Per-term assessment", "",
        "| Term / stable ID | Candidate | Code point and Unicode name | Verdict | Semantic fit and losses |",
        "| --- | --- | --- | --- | --- |",
    ]
    by_term = {row["term"]: row for row in candidates}
    for term in terms:
        row = by_term[term["id"].removeprefix("organon:")]
        glyph = row["glyph"]
        cells = [
            f"[{term['label']}](../ontology/ontology.md#{term['anchor']}) / `{term['id']}`",
            glyph or "—", describe(glyph) if glyph else "—",
            row["verdict"], row["reason"],
        ]
        lines.append("| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in cells) + " |")

    lines.extend(["", "## Candidate reuse and normalization", "",
                  "Reuse includes rejected candidates; it is not a proposed assignment. "
                  "Only trial rows would compete in a trial-only legend.", ""])
    for form in ("NFC", "NFKC"):
        groups = defaultdict(list)
        changes = []
        for row in candidates:
            if row["glyph"] is None:
                continue
            normalized = ud.normalize(form, row["glyph"])
            groups[normalized].append(f"{row['term']} ({row['verdict']})")
            if normalized != row["glyph"]:
                changes.append(f"{row['term']}: {row['glyph']} → {normalized}")
        lines.extend([f"### {form}", ""])
        for glyph, labels in sorted(groups.items()):
            if len(labels) > 1:
                lines.append(f"- {glyph}: {', '.join(labels)}.")
        lines.append("- Changed candidate strings: " + ("; ".join(changes) or "none") + ".")
        lines.append("")
    lines.extend([
        "### Boundary probes (not candidate assignments)", "",
        "These pairs deliberately distinguish byte/code-point identity from normalization identity.", "",
        "| Pair | Code points (left / right) | Equal after NFC? | Equal after NFKC? |",
        "| --- | --- | --- | --- |",
    ])
    for left, right in (("Ω", "Ω"), ("ℝ", "R"), ("₁", "1"), ("≠", "=\u0338")):
        codes = " / ".join(" ".join(f"U+{ord(c):04X}" for c in s) for s in (left, right))
        equal = [str(ud.normalize(form, left) == ud.normalize(form, right)).lower() for form in ("NFC", "NFKC")]
        lines.append(f"| {left} / {right} | {codes} | {equal[0]} | {equal[1]} |")
    lines.extend(["", "The audit does not test visual confusability, font coverage, "
                  "accessibility, human recognition or semantic equivalence.", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the atlas; default is check-only")
    args = parser.parse_args()
    try:
        catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
        expected = render(catalog, load_sources(catalog))
        if args.write:
            ATLAS.write_text(expected, encoding="utf-8")
        elif ATLAS.read_text(encoding="utf-8") != expected:
            raise ValueError("atlas is stale; run with --write")
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        print(f"Unicode study audit failed: {error}", file=sys.stderr)
        return 1
    print(f"Unicode study audit passed: {len(catalog['candidates'])} entries; "
          f"source hashes, exact coverage, UTF-8 and atlas checked (UCD {ud.unidata_version}).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
